# Pirate eye patch night-vision trick (spec mode v2.1)
SCRIPT = [
    "Did pirates wear eye patches to see in the dark?",
    "Here's the trick. Your eyes can take about twenty five minutes to adjust to darkness.",
    "So keep one eye covered in the bright sun.",
    "Then go below deck, and flip the patch.",
    "Boom! Instant night vision. Tests show it really works.",
    "But here's the twist: there's no record of any pirate actually doing it.",
    "So cover one eye tonight, and try it yourself.",
]
P = dict(body="#f3ead2", legs="#3a4a6b")
def pirate(x, y, sc, side=1, expr="smug", pose=None, ch=None, talk=True):
    return [guy(x=x, y=y, sc=sc, expr=expr, pose=pose, ch=ch or [], talk=talk, **P),
            art(f"bandana({x}, {y}, {sc})"),
            art(f"eyePatch({x}, {y}, {sc}, {side})")]
SHOTS = [
    shot(0,
         art("shipDeck(t, 0)"),
         *pirate(540, 1600, 2.0),
         label("WHY THE EYE PATCH?", None, y=230, col="#ffd23f"),
         bg="#9fd6ff", cam=(1.0, 1.04)),
    shot("trick",
         art("wallClock(540, 760, 240*k, t*30, 0, 1)", at="trick"),
         count("twenty", 25, "minutes", y=1180, fmt="{} MIN", size=130, col="#3d7bd9"),
         label("EYES ADJUST TO DARK", "adjust", y=230),
         bg="#e9e2d0"),
    shot("keep",
         art("shipDeck(t, 0)"),
         *pirate(540, 1600, 2.0, expr="angry"),
         pop("SUN!", "bright", x=820, y=520, size=90, col="#ffd23f"),
         label("COVERED = DARK-READY", "covered", y=230, col="#8fd3ff"),
         bg="#9fd6ff"),
    shot("Then",
         art("shipDeck(t, 1)"),
         art("lantern(820, 420, 1.0, t)"),
         *pirate(540, 1600, 2.0, side="(t > T.cut3 + 1.5 ? -1 : 1)", expr="determined"),
         pop("FLIP!", "flip", x=820, y=1000, size=110, col="#fff"),
         label("BELOW DECK", "below", y=230, col="#ffd23f"),
         bg="#1a1410"),
    shot("Boom",
         art("shipDeck(t, 1)"),
         art("coin(300, 1250, 90*k, t*3)", at="Instant"),
         art("coin(780, 1180, 90*k, t*3+1)", at="night"),
         *pirate(540, 1600, 1.8, side=-1, expr="laugh", pose="cheer"),
         label("NIGHT VISION!", "night", y=230, col="#7bc043"),
         check("works", ok=True, x=860, y=520, sc=1.2),
         bg="#1a1410"),
    shot("twist",
         art("shipDeck(t, 0)"),
         *pirate(540, 1600, 2.0, expr="confused", pose="shrug"),
         stamp("NONE", "record", y=520, col="#e8413a"),
         label("NO PIRATE RECORD", "pirate", y=230),
         bg="#9fd6ff"),
    shot("cover",
         guy(x=540, y=1480, sc=2.0, expr="smug", pose="point"),
         art("eyePatch(540, 1480, 2.0, 1)", at="cover"),
         label("TRY IT TONIGHT", "tonight", y=230, col="#ffd23f"),
         bg="#24294d"),
]
